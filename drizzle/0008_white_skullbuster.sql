CREATE TABLE `event_projections` (
	`id` varchar(160) NOT NULL,
	`eventKey` varchar(160) NOT NULL,
	`entityId` varchar(96),
	`symbol` varchar(32),
	`storylineKey` varchar(160),
	`eventType` varchar(64) NOT NULL,
	`title` text NOT NULL,
	`summary` text NOT NULL,
	`relationshipJson` text NOT NULL,
	`sentiment` enum('positive','neutral','negative','mixed') NOT NULL,
	`impactScore` int NOT NULL,
	`confidenceScore` int NOT NULL,
	`status` enum('active','stale','invalidated') NOT NULL,
	`sourceRecordId` varchar(96),
	`sourceUrl` text NOT NULL,
	`sourceKey` varchar(64) NOT NULL,
	`eventAt` timestamp NOT NULL,
	`detectedAt` timestamp NOT NULL,
	`staleAt` timestamp,
	`evidenceJson` text NOT NULL,
	`parserVersion` varchar(64) NOT NULL,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `event_projections_id` PRIMARY KEY(`id`),
	CONSTRAINT `event_projections_eventKey_unique` UNIQUE(`eventKey`)
);

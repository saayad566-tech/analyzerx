CREATE TABLE `autonomous_recommendations` (
	`id` varchar(160) NOT NULL,
	`eventKey` varchar(160) NOT NULL,
	`symbol` varchar(32) NOT NULL,
	`companyName` varchar(255) NOT NULL,
	`headline` text NOT NULL,
	`eventType` varchar(64) NOT NULL,
	`relationship` varchar(64) NOT NULL,
	`direction` varchar(32) NOT NULL,
	`impactScore` int NOT NULL,
	`confidenceScore` int NOT NULL,
	`impactLevel` varchar(32) NOT NULL,
	`status` varchar(32) NOT NULL,
	`reason` text NOT NULL,
	`factorsJson` text NOT NULL,
	`evidenceJson` text NOT NULL,
	`sourceTimestamp` timestamp NOT NULL,
	`eventTimestamp` timestamp NOT NULL,
	`detectedAt` timestamp NOT NULL,
	`lastSeenAt` timestamp NOT NULL,
	`staleAt` timestamp,
	`invalidatedAt` timestamp,
	`lastNotifiedAt` timestamp,
	`scoreVersion` varchar(32) NOT NULL,
	`routeTarget` varchar(255) NOT NULL,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `autonomous_recommendations_id` PRIMARY KEY(`id`),
	CONSTRAINT `autonomous_recommendations_eventKey_unique` UNIQUE(`eventKey`)
);

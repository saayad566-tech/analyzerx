import "../scripts/load-env.js";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { analyzeFundamentals } from "../server/fundamental-analysis";
import { fundamentalAnalysisToMarkdown, reportFileName } from "../server/research-report";

const symbols = ["ADANIENT", "RELIANCE", "TCS", "HDFCBANK", "TATAPOWER", "INFY", "APOLLOHOSP", "LT", "AAPL", "SAP.DE"];
const outputDir = path.resolve("artifacts/ten-stock-market-event-intelligence");

async function mapWithConcurrency<T, R>(items: T[], limit: number, worker: (item: T) => Promise<R>) {
  const output: R[] = [];
  let cursor = 0;
  async function run() {
    while (cursor < items.length) {
      const index = cursor++;
      output[index] = await worker(items[index]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, () => run()));
  return output;
}

function countUnavailable(markdown: string) {
  return (markdown.match(/Unavailable/g) ?? []).length;
}

async function main() {
  await mkdir(outputDir, { recursive: true });
  const results = await mapWithConcurrency(symbols, 3, async (symbol) => {
    const report = await analyzeFundamentals(symbol);
    const news = { articles: [], freshArticleCount: 0, stale: false };
    const markdown = fundamentalAnalysisToMarkdown(report, news.articles);
    const filePath = path.join(outputDir, reportFileName(report));
    await writeFile(filePath, markdown, "utf8");
    return {
      requestedSymbol: symbol,
      resolvedSymbol: report.resolvedSymbol,
      companyName: report.companyName,
      score: report.score,
      coverage: report.coverage,
      pillarScores: report.categories.map((category) => ({ label: category.label, score: category.score, max: category.max, basis: category.basis })),
      currentPrice: report.fairValue.currentPrice,
      fairValueBasis: report.fairValue.basis,
      history: { revenue: report.history.revenue.length, eps: report.history.eps.length, cashFlow: report.history.cashFlow.length },
      sourceCount: report.sources.length,
      unavailableMentions: countUnavailable(markdown),
      newsArticles: news.articles.length,
      newsFreshArticleCount: news.freshArticleCount,
      newsStale: news.stale,
      file: path.basename(filePath),
    };
  });
  const summary = `# AnalyzerX — Ten-Stock Report Audit

**Publisher:** AnalyzerX  
**Audit timestamp:** ${new Date().toISOString()}  
**Scope:** Ten separate platform-generated equity reports; Manus was used only for software verification.

## Acceptance Criteria

Each report must include the five analytical pillars, numerical ranking and evidence basis, company identity and market metadata, current price status, financial metrics, cash-flow analysis, valuation anchors, risk and catalyst sections, company scope, future-plan evidence, workforce provenance, historical chart data, news/data freshness, source hierarchy, and explicit verified/estimated/unavailable labels. A missing value may be unavailable, but it must never be silently rendered as zero or fabricated.

## Report Matrix

| Symbol | Resolved | Company | Overall | Coverage | Verified / Estimated / Unavailable | Price | Revenue / EPS / CFO periods | News | Sources | Unavailable mentions | File |
|---|---|---|---:|---:|---|---|---:|---:|---:|---:|---|
${results.map((item) => `| ${item.requestedSymbol} | ${item.resolvedSymbol} | ${item.companyName} | ${item.score}/100 | ${item.coverage.score}/100 | ${item.coverage.verified} / ${item.coverage.estimated} / ${item.coverage.unavailable} | ${item.currentPrice === null ? "Unavailable" : item.currentPrice} | ${item.history.revenue} / ${item.history.eps} / ${item.history.cashFlow} | ${item.newsArticles} (${item.newsFreshArticleCount} fresh) | ${item.sourceCount} | ${item.unavailableMentions} | [${item.file}](./${item.file}) |`).join("\n")}

## Five-Pillar Ranking Detail

${results.map((item) => `### ${item.companyName} (${item.resolvedSymbol})\n\n${item.pillarScores.map((pillar, index) => `${index + 1}. **${pillar.label}: ${pillar.score}/${pillar.max}** — ${pillar.basis}`).join("  \n")}\n`).join("\n")}

## Quality Findings

The matrix distinguishes data availability from analytical score. A complete score can still contain estimated or unavailable evidence; the coverage score makes that limitation visible. Current-price, valuation, financial-period, and source fields are checked independently. Reports with unavailable history retain explicit empty-chart states rather than invented points.

## Platform Publishing Boundary

These artifacts are generated by the AnalyzerX report formatter and carry the platform’s own report title, provenance, disclaimer, and analysis timestamp. Manus is not presented as the publisher or research provider.
`;
  await writeFile(path.join(outputDir, "ten-stock-audit-summary.md"), summary, "utf8");
  console.log(JSON.stringify({ outputDir, symbols, results }, null, 2));
}

void main().catch((error) => { console.error(error); process.exitCode = 1; });
